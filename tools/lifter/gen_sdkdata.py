"""Extract the values of data symbols the game imports from the SDK module (nn::util constants and
tables, nn::hid ids) out of the real `sdk` binary, and emit them as C arrays in sdkdata.c."""
import os
import struct

SDK = os.path.join(os.environ['RECOMP_BIN'], 'sdk.elf') if os.environ.get('RECOMP_BIN') else r'..\binaries\13.0.4\sdk.elf'   # RECOMP_BIN: scripts/setup.py
d = open(SDK, 'rb').read()
OFF = 0x1000
# locate .dynsym / .dynstr through the section headers nso2elf wrote
shoff, = struct.unpack_from('<Q', d, 0x28)
shnum, shstrndx = struct.unpack_from('<HH', d, 0x3c)
secs = [struct.unpack_from('<IIQQQQIIQQ', d, shoff + i * 64) for i in range(shnum)]
strtab = d[secs[shstrndx][4]:secs[shstrndx][4] + secs[shstrndx][5]]
by_name = {strtab[s[0]:strtab.index(b'\0', s[0])].decode(): s for s in secs}
sym_off, sym_size = by_name['.dynsym'][4], by_name['.dynsym'][5]
str_off = by_name['.dynstr'][4]
syms = {}
for i in range(sym_size // 24):
    name_off, info, other, shndx, value, size = struct.unpack_from('<IBBHQQ', d, sym_off + i * 24)
    name = d[str_off + name_off:d.index(b'\0', str_off + name_off)].decode('latin-1')
    if shndx and (info & 0xf) == 1:                      # defined OBJECT
        syms[name] = (value, size)

wanted = [l.strip() for l in open('imports_all.txt') if l.startswith(('_ZN2nn4util', '_ZN2nn3hid6NpadId'))]
out, found = [], []
for name in wanted:
    if name in syms and 0 < syms[name][1] <= 1 << 20:
        value, size = syms[name]
        found.append((name, d[OFF + value:OFF + value + size]))
with open('sdkdata.c', 'w') as f:
    f.write('/* generated by gen_sdkdata.py from the real sdk module -- do not edit */\n#include "hostrt.h"\n\n')
    for k, (name, data) in enumerate(found):
        f.write('static const unsigned char d%d[] = {%s};\n' % (k, ','.join(str(b) for b in data)))
    f.write('\nconst SdkData sdk_data[] = {\n')
    for k, (name, data) in enumerate(found):
        f.write('  { "%s", d%d, %d },\n' % (name, k, len(data)))
    f.write('};\nconst int sdk_data_count = %d;\n' % len(found))
for name, data in found:
    print('%6d  %s' % (len(data), name))
print('%d data symbols extracted' % len(found))
